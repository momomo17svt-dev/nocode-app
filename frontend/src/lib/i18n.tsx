const DYNAMIC_PATTERNS: Array<[RegExp, (...matches: string[]) => string]> = [
  [/^APIエラー\s*\((\d+)\)$/, (_, status) => `API error (${status})`],
  [/^ダウンロードに失敗しました\s*\((\d+)\)$/, (_, status) => `Download failed (${status})`],
  [/^(\d[\d,]*)\s*件$/, (_, count) => `${count} items`],
  [/^(\d[\d,]*)\s*名$/, (_, count) => `${count} users`],
  [/^(\d[\d,]*)\s*項目$/, (_, count) => `${count} fields`],
  [/^全\s*(\d[\d,]*)\s*件$/, (_, count) => `${count} total`],
  [/^未完了\s*(\d[\d,]*)\s*件$/, (_, count) => `${count} incomplete`],
  [/^処理中\s*(\d[\d,]*)\s*件$/, (_, count) => `${count} processing`],
  [/^順番待ち\s*(\d[\d,]*)\s*件$/, (_, count) => `${count} queued`],
  [/^ページ\s*(\d+)\s*\/\s*(\d+)$/, (_, page, pages) => `Page ${page} of ${pages}`],
  [/^(.+)を削除$/, (_, name) => `Delete ${name}`],
  [/^(.+)を編集$/, (_, name) => `Edit ${name}`],
  [/^(.+)を開く$/, (_, name) => `Open ${name}`],
  [/^(.+)をAIに質問$/, (_, name) => `Ask AI about ${name}`],
  [/^(.+)を解除$/, (_, name) => `Remove ${name}`],
  [/^(\d+)文字以上$/, (_, count) => `${count} characters or more`],
  [
    /^ログイン試行回数が上限に達しました。あと(\d+)分後に再試行してください$/,
    (_, minutes) => `Too many failed sign-in attempts. Try again in ${minutes} minute(s).`,
  ],
];

function preserveWhitespace(source: string, translated: string): string {
  const leading = source.match(/^\s*/)?.[0] ?? '';
  const trailing = source.match(/\s*$/)?.[0] ?? '';
  return `${leading}${translated}${trailing}`;
}

export function translate(source: string): string {
  if (currentLanguage !== 'en' || !source) return source;
  const trimmed = source.trim();
  if (!trimmed) return source;
  const exact = EN[trimmed];
  if (exact !== undefined) return preserveWhitespace(source, exact);
  for (const [pattern, replacement] of DYNAMIC_PATTERNS) {
    const match = trimmed.match(pattern);
    if (match) return preserveWhitespace(source, replacement(...match));
  }
  return source;
}

export function formatDateTime(value: string | number | Date): string {
  return new Intl.DateTimeFormat(getLocale(), { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(value));
}

export function formatDate(value: string | number | Date): string {
  return new Intl.DateTimeFormat(getLocale(), { dateStyle: 'medium' }).format(new Date(value));
}

export function formatNumber(value: number): string {
  return value.toLocaleString(getLocale());
}

type SavedNode = { original: string; translated: string };
const savedText = new WeakMap<Text, SavedNode>();
const savedAttributes = new WeakMap<Element, Map<string, SavedNode>>();
const ATTRIBUTES = ['placeholder', 'title', 'aria-label'];

function shouldIgnore(node: Node): boolean {
  const element = node.nodeType === Node.ELEMENT_NODE ? node as Element : node.parentElement;
  return !!element?.closest('[data-i18n-ignore], code, pre, textarea, script, style');
}

function localizeTextNode(node: Text, language: Language): void {
  if (shouldIgnore(node)) return;
  const value = node.nodeValue ?? '';
  const saved = savedText.get(node);
  if (language === 'ja') {
    if (saved && value === saved.translated) node.nodeValue = saved.original;
    savedText.delete(node);
    return;
  }
  if (saved && value === saved.translated) return;
  const translated = translate(value);
  if (translated !== value) {
    savedText.set(node, { original: value, translated });
    node.nodeValue = translated;
  } else if (saved) {
    savedText.delete(node);
  }
}

function localizeElement(element: Element, language: Language): void {
  if (shouldIgnore(element)) return;
  const values = savedAttributes.get(element) ?? new Map<string, SavedNode>();
  for (const attribute of ATTRIBUTES) {
    const value = element.getAttribute(attribute);
    if (value === null) continue;
    const saved = values.get(attribute);
    if (language === 'ja') {
      if (saved && value === saved.translated) element.setAttribute(attribute, saved.original);
      values.delete(attribute);
      continue;
    }
    if (saved && value === saved.translated) continue;
    const translated = translate(value);
    if (translated !== value) {
      values.set(attribute, { original: value, translated });
      element.setAttribute(attribute, translated);
    } else {
      values.delete(attribute);
    }
  }
  if (values.size > 0) savedAttributes.set(element, values);
  else savedAttributes.delete(element);
}

function localizeTree(root: Node, language: Language): void {
  if (root.nodeType === Node.TEXT_NODE) localizeTextNode(root as Text, language);
  if (root.nodeType === Node.ELEMENT_NODE) localizeElement(root as Element, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current.nodeType === Node.TEXT_NODE) localizeTextNode(current as Text, language);
    else localizeElement(current as Element, language);
    current = walker.nextNode();
  }
}

function installDocumentLocalizer(language: Language): () => void {
  document.documentElement.lang = language;
  document.title = language === 'en' ? 'No-Code App' : 'ノーコードApp';
  localizeTree(document.body, language);
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') localizeTextNode(mutation.target as Text, language);
      if (mutation.type === 'attributes') localizeElement(mutation.target as Element, language);
      mutation.addedNodes.forEach((node) => localizeTree(node, language));
    }
  });
  observer.observe(document.body, {
    childList: true,
    subtree: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRIBUTES,
  });
  return () => observer.disconnect();
}

interface I18nValue {
  language: Language;
  locale: 'ja-JP' | 'en-US';
  setLanguage: (language: Language) => void;
  t: (source: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(subscribe, getLanguage, () => 'ja' as Language);
  useEffect(() => installDocumentLocalizer(language), [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    locale: language === 'en' ? 'en-US' : 'ja-JP',
    setLanguage,
    t: translate,
  }), [language]);

  // Remount the current screen so locale-sensitive dates and numbers refresh too.
  return <I18nContext.Provider value={value}><div className="contents" key={language}>{children}</div></I18nContext.Provider>;
}

export function useLanguage(): I18nValue {
  const value = useContext(I18nContext);
  const language = useSyncExternalStore(subscribe, getLanguage, () => 'ja' as Language);
  const fallback = useMemo<I18nValue>(() => ({
    language,
    locale: language === 'en' ? 'en-US' : 'ja-JP',
    setLanguage,
    t: translate,
  }), [language]);
  // Standalone component tests and embeddable public screens may render without
  // the root provider. They still get a functional language switch.
  return value ?? fallback;
}
